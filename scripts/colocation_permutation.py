"""Spatially constrained significance test for UGPI-SH co-location (Moran spectral randomisation).

Surrogates of one layer are generated by randomly flipping the signs of its coefficients on the
Moran eigenvector maps of a queen-contiguity graph of the 10 km grid (Wagner and Dray 2015,
'singleton' method). This preserves the layer's Moran's I exactly while breaking its alignment with
the other layer. The high-high count at Q75 and Q90 is recomputed for each surrogate.
"""
from pathlib import Path

import geopandas as gpd
import matplotlib
import numpy as np
import pandas as pd

matplotlib.use('Agg')
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parents[1]
V2 = ROOT / 'data/processed/risk_index/cgsri_grid10km_v2.gpkg'
OUT = ROOT / 'outputs/tables/revision_checks'
FIG = ROOT / 'outputs/figures/figS6_colocation_null.png'
N_SURR = 9999
rng = np.random.default_rng(20261112)

g = gpd.read_file(V2)
n = len(g)
c, r = g['col_id'].values, g['row_id'].values
W = ((np.abs(c[:, None] - c[None, :]) <= 1) & (np.abs(r[:, None] - r[None, :]) <= 1)).astype(float)
np.fill_diagonal(W, 0)
H = np.eye(n) - 1.0 / n
vals, vecs = np.linalg.eigh(H @ W @ H)
keep = np.abs(vals) > 1e-8
V = vecs[:, keep]


def morans_i(x):
    z = x - x.mean()
    return n / W.sum() * (z @ W @ z) / (z @ z)


def surrogates(x):
    z = (x - x.mean()) / x.std()
    coef = V.T @ z
    signs = rng.choice([-1.0, 1.0], size=(N_SURR, coef.size))
    return (signs * coef) @ V.T


def hh(a, b, q):
    return int(((a >= np.quantile(a, q)) & (b >= np.quantile(b, q))).sum())


u = g['ugpi_urban_only'].values
s = g['sub_hazard'].values
rows, null = [], {}
for q in (0.75, 0.90):
    obs = hh(u, s, q)
    for label, x, y in [('UGPI randomised', u, s), ('SH randomised', s, u)]:
        surr = surrogates(x)
        counts = np.array([hh(sx, y, q) for sx in surr])
        p = (1 + (counts >= obs).sum()) / (N_SURR + 1)
        null[(q, label)] = (counts, obs)
        rows.append(dict(threshold=f'Q{int(q * 100)}', randomised=label, observed_hh=obs,
                         null_mean=round(counts.mean(), 1), null_95pct=float(np.percentile(counts, 95)),
                         p_one_sided=round(p, 4)))
moran = dict(UGPI=round(morans_i(u), 3), SH=round(morans_i(s), 3))
res = pd.DataFrame(rows)
res.to_csv(OUT / 'colocation_msr_test.csv', index=False)
print("Moran's I:", moran)
print(res.to_string(index=False))
chk = surrogates(u)[:200]
print("surrogate Moran's I (UGPI) mean %.3f sd %.4f" % (np.mean([morans_i(x) for x in chk]), np.std([morans_i(x) for x in chk])))

fig, axes = plt.subplots(1, 2, figsize=(10, 3.6))
for ax, q, lab in zip(axes, (0.75, 0.90), 'ab'):
    counts, obs = null[(q, 'UGPI randomised')]
    ax.hist(counts, bins=np.arange(counts.min(), counts.max() + 2) - 0.5, color='#9ECAE1', edgecolor='white')
    ax.axvline(obs, color='#A50026', lw=2, label=f'observed = {obs}')
    p = res[(res.threshold == f'Q{int(q * 100)}') & (res.randomised == 'UGPI randomised')].p_one_sided.iloc[0]
    ax.set_title(f'({lab}) Q{int(q * 100)}', loc='left', fontsize=9, fontweight='bold')
    ax.set_xlabel('High-high count under spatially constrained null')
    ax.legend(fontsize=8)
axes[0].set_ylabel('Surrogates')
plt.tight_layout()
plt.savefig(FIG, dpi=300, bbox_inches='tight')
print('saved', FIG)
